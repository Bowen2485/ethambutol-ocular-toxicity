# -*- coding: utf-8 -*-
"""
Locate the JADER archives on the correct PMDA page.

The first attempt read .../suspected-adr/0003.html, which is a general adverse-reaction
index.  The link inventory pointed instead to .../suspected-adr/0005.html, whose anchor
text is "副作用が疑われる症例報告に関する情報" - information on case reports of suspected
adverse reactions.  That is the JADER download page.

The page carries several tables, one per year, each listing the quarterly files:
    demo   the case, with age, sex and report date
    drug   the drugs in that case, with the role code
    reac   the reactions, as MedDRA preferred terms
Those three are exactly what the disproportionality analysis needs, and they match the
FAERS tables in structure, so the same 2x2 logic applies without modification.

This lists the files and their URLs.  Nothing is downloaded.
"""
from __future__ import annotations

import re
import ssl
import urllib.error
import urllib.parse
import urllib.request
from html.parser import HTMLParser

CTX = ssl.create_default_context()
CTX.check_hostname = False
CTX.verify_mode = ssl.CERT_NONE
UA = {"User-Agent": "Mozilla/5.0 (research)"}
PAGE = ("https://www.pmda.go.jp/safety/info-services/drugs/adr-info/"
        "suspected-adr/0005.html")


class Links(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.items: list[tuple[str, str]] = []
        self._cur, self._text, self._in = None, [], False

    def handle_starttag(self, tag, attrs):
        d = dict(attrs)
        if tag == "a" and d.get("href"):
            self._in, self._cur, self._text = True, d["href"], []

    def handle_data(self, data):
        if self._in:
            self._text.append(data)

    def handle_endtag(self, tag):
        if tag == "a" and self._in:
            self.items.append((self._cur or "",
                               " ".join("".join(self._text).split())))
            self._in = False


try:
    req = urllib.request.Request(PAGE, headers=UA)
    with urllib.request.urlopen(req, timeout=90, context=CTX) as r:
        html = r.read().decode("utf-8", "replace")
except urllib.error.HTTPError as exc:
    raise SystemExit(f"HTTP {exc.code} for {PAGE}")
except Exception as exc:  # noqa: BLE001
    raise SystemExit(f"{type(exc).__name__} for {PAGE}")

print(f"page: {PAGE}")
print(f"length: {len(html):,} characters")

p = Links()
p.feed(html)
print(f"anchors: {len(p.items)}")

# JADER files are distributed as zipped text or excel, one per quarter per table
FILE_EXT = (".zip", ".xls", ".xlsx", ".csv", ".txt", ".gz", ".lzh")
data = []
for href, text in p.items:
    low = href.lower()
    if any(low.endswith(e) or e + "?" in low for e in FILE_EXT):
        data.append((urllib.parse.urljoin(PAGE, href), text))

print()
print("=" * 96)
print(f"Data files linked: {len(data)}")
print("=" * 96)
for url, text in data[:60]:
    name = url.rsplit("/", 1)[-1]
    print(f"  {text[:44]:44s} {name[:62]}")

# also look for the year headings, which tell us how far the series runs
years = sorted({int(y) for y in re.findall(r"(20[0-2][0-9])\s*年", html)})
print()
print(f"year headings found on the page: {years[:4]} ... {years[-6:]}" if years else
      "no year headings parsed")

# the three tables are usually named in the anchor text; confirm they are present
print()
print("=" * 96)
print("Table types referenced")
print("=" * 96)
for key, label in (("demo", "demo - case information"),
                   ("drug", "drug - drugs per case"),
                   ("reac", "reac - reactions per case")):
    n = sum(1 for u, t in data if key in u.lower() or key in t.lower())
    print(f"  {label:32s} {n} links match")

if not data:
    print()
    print("No file links parsed.  The listing may be generated by script; in that case")
    print("the archive URLs have to be read from the page source directly, or the files")
    print("obtained through the PMDA file server listing.")
    # show any link that looks like a file path even without a known extension
    cand = [(h, t) for h, t in p.items
            if re.search(r"/(files|contents)/", h) or re.search(r"\.(pdf|html?)$", h)
            and "jader" in (h + t).lower()]
    print(f"  fallback candidates: {len(cand)}")
    for h, t in cand[:20]:
        print(f"      {t[:50]:50s} {h[:86]}")
