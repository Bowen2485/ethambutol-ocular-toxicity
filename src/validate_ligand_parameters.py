def strict_rotatable_bonds(m) -> int:
    """
    Count rotatable bonds by the strict definition.

    A single, non-ring bond between two heavy atoms, each with at least two heavy
    neighbours.  Terminal methyls are excluded because the carbon has one heavy
    neighbour; the two C-CH2OH bonds are counted because the CH2 has two, which is the
    same rule RDKit applies and the same value it returns (9).  An earlier version of
    this comment asserted that a hand count gave 7; that hand count was wrong, and the
    bond-by-bond listing in src/rotatable_bond_definitions.py is what settled it.
    """
    n = 0
    for b in m.GetBonds():
        if b.GetBondType() != Chem.BondType.SINGLE or b.IsInRing():
            continue
        a1, a2 = b.GetBeginAtom(), b.GetEndAtom()
        if a1.GetAtomicNum() == 1 or a2.GetAtomicNum() == 1:
            continue
        if len([x for x in a1.GetNeighbors() if x.GetAtomicNum() > 1]) < 2:
            continue
        if len([x for x in a2.GetNeighbors() if x.GetAtomicNum() > 1]) < 2:
            continue
        n += 1
    return n


