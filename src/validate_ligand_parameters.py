"""
Validate the small-molecule parameters used in the all-atom simulations.

Why this is needed
    The all-atom runs used GAFF-2.11 with AM1-BCC charges, generated by antechamber.
    Nothing in the project checks those parameters.  A reviewer's question - how do you
    know the ligand was described correctly - currently has no answer, and the entire MD
    conclusion rests on it, so the check has to be made rather than asserted.

What can be validated without a crystal structure of ethambutol
    The strongest test would be whether the force field reproduces an experimental
    geometry of the drug.  No such structure is in the project and none is in the PDB
    for the free drug, so the tests below are the ones that remain:

    1. Composition and protonation.  The ligand file has 38 atoms; C10H24N2O2 has 38.
       Whether the molecule is neutral or diprotonated changes the charge by 2e and
       therefore every electrostatic interaction in the simulation, and the two forms
       differ in hydrogen count, so the composition identifies which was simulated.
    2. Rotatable-bond sampling.  Ethambutol is small and flexible.  A 1 ns trajectory
       samples a limited part of its torsional space, and the number of torsions sets a
       lower bound on what a longer run would add.  This quantifies how much of the
       conclusion depends on run length.
    3. Conformer coverage.  Independent conformer generation gives the accessible
       torsional states, against which the single docked-and-simulated geometry can be
       compared: if the simulated geometry sits in a plausible well, the parameters did
       not distort it.
    4. Validation against a reference structure.  The docking validation panel already
       contains crystal ligands for seven complexes.  Comparing each crystal ligand's
       geometry with the geometry of the same molecule after force-field relaxation
       tests the parameter set on molecules of similar size, which is the closest thing
       to a direct test available.
"""
