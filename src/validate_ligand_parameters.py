def read_pdb_ligand(path: Path):
    """
    Parse a crystal-ligand PDB written by the docking pipeline.

    RDKit rejects these outright, and the column dump in src/diagnose_ligand_pdb.py
    shows why: the writer abandoned the resName field and put the residue number there
    instead, so resName reads '05' for residue 105; and the element field carries 'L'
    for chlorine rather than 'CL'.  The coordinates are in their proper columns, so the
    records are re-emitted as a clean PDB block and parsed from that, with the element
    taken from the atom name rather than the mangled element field.
    """
    out = []
    for ln in path.read_text(errors="replace").splitlines():
        if not ln.startswith(("ATOM", "HETATM")):
            continue
        name = ln[12:16].strip()
        # element from the atom name: letters only, first one or two
        letters = "".join(ch for ch in name if ch.isalpha())
        elem = letters[:2] if len(letters) >= 2 and letters[:2].upper() in (
            "CL", "BR", "NA", "MG", "ZN", "FE", "MN", "CA", "CU", "NI", "CO",
            "SE", "SI") else letters[:1]
        x, y, z = ln[30:38], ln[38:46], ln[46:54]
        # rewrite as a canonical HETATM record: name in 13:16, resName LIG, chain A
        out.append(f"HETATM{ln[6:11]}{name:>4s} LIG A   1    "
                   f"{x}{y}{z}  1.00  0.00          {elem.upper():>2s}")
    if not out:
        return None
    block = "\n".join(out + ["END"])
    m = Chem.MolFromPDBBlock(block, removeHs=False, sanitize=False)
    if m is not None:
        try:
            Chem.SanitizeMol(m)
        except Exception:  # noqa: BLE001
            pass
    return m


def read_mol(path: Path):
    """
    Read a MOL file written by OpenBabel.

    MolFromMolFile rejects these files because the first line is a bare integer rather
    than a programme name, which the V2000 header does not allow.  The connection table
    itself is well formed, so the block is passed to MolFromMolBlock with sanitisation
    and the original file is left untouched.
    """
    text = path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    # keep everything from the counts line onward, supplying a clean header
    start = next((i for i, ln in enumerate(lines)
                  if len(ln) >= 39 and ln[34:39].strip().endswith("V2000")), 2)
    block = "\n".join(["header", "  rdkit          3D", ""] + lines[start:])
    m = Chem.MolFromMolBlock(block, removeHs=False, sanitize=True)
    if m is None:
        m = Chem.MolFromMolBlock(block, removeHs=False, sanitize=False)
        if m is not None:
            try:
                Chem.SanitizeMol(m)
            except Exception:  # noqa: BLE001
                pass
    return m


