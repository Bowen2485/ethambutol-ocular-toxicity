molh = Chem.AddHs(NEUTRAL)
ps = AllChem.ETKDGv3()
ps.randomSeed = 0xC0FFEE
ps.pruneRmsThresh = 0.25
cids = list(AllChem.EmbedMultipleConfs(molh, numConfs=200, params=ps))
energies = []
for cid in cids:
    props = AllChem.MMFFGetMoleculeProperties(molh)
    if props is None:
        continue
    ff = AllChem.MMFFGetMoleculeForceField(molh, props, confId=cid)
    if ff is None:
        continue
    ff.Minimize(maxIts=2000)
    energies.append((ff.CalcEnergy(), cid))
energies.sort()
print(f"  embedded conformers         : {len(cids)}")
